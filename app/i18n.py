def t(key: str, lang: str = "zh", **kwargs) -> str:
    pair = _STRINGS.get(key)
    if pair is None:
        return key
    text = pair[1] if lang == "en" else pair[0]
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text


def keys():
    return sorted(_STRINGS)
